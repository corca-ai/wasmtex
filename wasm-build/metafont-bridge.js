/* =============================================================================
 * metafont-bridge.js — mktexpk, mktextfm and mktexmf for the engine workers
 * =============================================================================
 *
 * A font without an outline exists only as Metafont source. TeX Live forks mktexpk
 * to turn it into a bitmap, which a worker cannot do, so this runs WebAssembly
 * Metafont and GFtoPK inside the engine's synchronous file lookup instead. The build
 * appends this file to both generated modules in wasmtex-metafont.js, and a controller
 * imports that only when a document asks for such a font.
 *
 * Output matches TeX Live byte for byte: same mode, resolution and magnification as
 * mktexpk, the same generated sources as mktexmf, and a fixed date because Metafont
 * seeds `uniformdeviate` from the clock.
 * ========================================================================== */
;(() => {
  const TOOL_DIR = '/mf'
  const BASE_DPI = 600
  const MODE = 'ljfour'
  const MF_FORMAT = 13
  const FIXED_EPOCH = '1577836800'
  const CONFIG = 'MFINPUTS=.\nMFBASES=.\nTFMFONTS=.\nGFFONTS=.\n'
  // mktexmf's short names for the magsteps.
  const MAGSTEP_SIZES = {
    11: '10.95', 14: '14.4', 17: '17.28', 20: '20.74', 25: '24.88', 30: '29.86', 36: '35.83',
  }

  const mirrorSources = new Map()
  const made = new Map()
  let base = null

  function mirrorSource(file) {
    if (mirrorSources.has(file)) return mirrorSources.get(file)
    const xhr = new XMLHttpRequest()
    xhr.open('GET', `${self.texlive_endpoint}pdftex/${MF_FORMAT}/${encodeURIComponent(file)}`, false)
    xhr.responseType = 'arraybuffer'
    try {
      xhr.send()
    } catch {
      return null
    }
    const bytes = xhr.status === 200 ? new Uint8Array(xhr.response) : null
    mirrorSources.set(file, bytes)
    return bytes
  }

  function projectFile(file, host) {
    const path = `${host.workRoot}/${file}`
    return host.fs.analyzePath(path).exists ? host.fs.readFile(path) : null
  }

  function rootSource(root, host) {
    return projectFile(root, host) ?? mirrorSource(root)
  }

  /** mktexmf: a font named after a size of a parametric family has no file of its own. */
  function generatedSource(name, host) {
    const family = name.replace(/\d*$/, '')
    const pointSize = name.slice(family.length)
    if (!pointSize) return null
    const sauter = rootSource(`b-${family}.mf`, host) ? `b-${family}` : null
    const rootFile = sauter
      ? `${sauter}.mf`
      : /^csso12[0-5][0-9]$/.test(name)
        ? null
        : /^(cs|lcsss|icscsc|icstt|ilcsss)/.test(family)
          ? 'cscode.mf'
          : /^(wn[bcdfirstuv]|rx[bcdfiorstuvx][bcfhilmostx]$|l[abcdhl][bcdfiorstuvx])/.test(family)
            ? `${name.slice(0, 2)}codes.mf`
            : `${family}.mf`
    if (!rootFile || !rootSource(rootFile, host)) return null
    const size =
      MAGSTEP_SIZES[pointSize] ??
      (/^\d{4,5}$/.test(pointSize) ? pointSize.replace(/(..)$/, '.$1') : pointSize)
    if (/^(ec|tc)/.test(name)) {
      return `if unknown exbase: input exbase fi;\ngensize:=${size};\ngenerate ${family};\n`
    }
    if (/^dc/.test(name)) {
      return `if unknown dxbase: input dxbase fi;\ngensize:=${size};\ngenerate ${family};\n`
    }
    if (/^(cs|lcsss|icscsc|icstt|ilcsss)/.test(name)) return 'input cscode\nuse_driver;\n'
    if (/^(wn[bcdfirstuv]|rx[bcdfiorstuvx][bcfhilmostx]|l[abcdhl][bcdfiorstuvx])/.test(name)) {
      return 'input fikparm;\n'
    }
    if (/^g[lmorst][bijmtwx][cilnoru]/.test(name)) {
      return '% generated by mktexmf\ninput cbgreek;\n'
    }
    return `design_size := ${size};\ninput ${sauter ?? family};\n`
  }

  function resolveSource(name, host, used) {
    const file = name.includes('.') ? name : `${name}.mf`
    const local = projectFile(file, host)
    if (local) {
      used.project = true
      return [file, local]
    }
    const mirrored = mirrorSource(file)
    if (mirrored) return [file, mirrored]
    const generated = name.includes('.') ? null : generatedSource(name, host)
    return generated ? [file, new TextEncoder().encode(generated)] : null
  }

  function runTool(factory, args, inputs, findFile) {
    const tool = factory({
      thisProgram: `${TOOL_DIR}/mf`,
      print() {},
      printErr() {},
      quit(_status, error) {
        throw error
      },
      preRun: [
        (module) => {
          module.ENV.FORCE_SOURCE_DATE = '1'
          module.ENV.SOURCE_DATE_EPOCH = FIXED_EPOCH
        },
      ],
      findFile,
    })
    tool.FS.mkdir(TOOL_DIR)
    tool.FS.chdir(TOOL_DIR)
    tool.FS.writeFile(`${TOOL_DIR}/mf`, '')
    tool.FS.writeFile(`${TOOL_DIR}/texmf.cnf`, CONFIG)
    for (const [name, bytes] of inputs) tool.FS.writeFile(`${TOOL_DIR}/${name}`, bytes)
    try {
      tool.callMain(args)
    } catch (error) {
      if (error?.name !== 'ExitStatus') throw error
    }
    return tool
  }

  function runMetafont(args, inputs, host, used) {
    return runTool(self.createWasmtexMetafont, args, inputs, (tool, name, format) => {
      if (format !== MF_FORMAT) return null
      const found = resolveSource(name, host, used)
      if (!found) return null
      const path = `${TOOL_DIR}/${found[0]}`
      tool.FS.writeFile(path, found[1])
      return path
    })
  }

  function baseFile(host) {
    if (base) return base
    const tool = runMetafont(
      ['-ini', '-jobname=mf', '\\input plain; input modes; dump'],
      [],
      host,
      {},
    )
    if (tool.FS.analyzePath(`${TOOL_DIR}/mf.base`).exists) {
      base = tool.FS.readFile(`${TOOL_DIR}/mf.base`)
    }
    return base
  }

  function runFont(name, mag, host, used) {
    const baseBytes = baseFile(host)
    if (!baseBytes) return null
    return runMetafont(
      ['-base=mf', `\\mode:=${MODE}; mag:=${mag}; nonstopmode; input ${name}`],
      [['mf.base', baseBytes]],
      host,
      used,
    )
  }

  /** Runs `build` once per key unless a project source may have changed the answer. A
   *  restored heap can drop the cache directory, so a remembered path must still exist. */
  function remember(key, host, build) {
    const known = made.get(key)
    if (known === null || (known && host.fs.analyzePath(known).exists)) return known
    const used = { project: false }
    const path = build(used)
    if (!used.project) made.set(key, path)
    return path
  }

  self.wasmtexMetafont = {
    makePk(name, dpi, host) {
      const stored = `${name}.${dpi}pk`
      if (projectFile(stored, host)) return `${host.workRoot}/${stored}`
      return remember(`pk/${dpi}/${name}`, host, (used) => {
        const mag = `${Math.floor(dpi / BASE_DPI)}+${dpi % BASE_DPI}/${BASE_DPI}`
        const font = runFont(name, mag, host, used)
        const gf = font?.FS.readdir(TOOL_DIR).find((file) => /\.\d+gf$/.test(file))
        if (!gf) return null
        const converted = runTool(
          self.createWasmtexGftopk,
          [`./${gf}`, 'font.pk'],
          [[gf, font.FS.readFile(`${TOOL_DIR}/${gf}`)]],
        )
        if (!converted.FS.analyzePath(`${TOOL_DIR}/font.pk`).exists) return null
        const path = `${host.cacheRoot}/${stored}`
        host.fs.writeFile(path, converted.FS.readFile(`${TOOL_DIR}/font.pk`))
        return path
      })
    },

    makeTfm(name, host) {
      return remember(`tfm/${name}`, host, (used) => {
        const font = runFont(name, '1', host, used)
        const tfm = `${TOOL_DIR}/${name}.tfm`
        if (!font?.FS.analyzePath(tfm).exists) return null
        const path = `${host.cacheRoot}/${name}.tfm`
        host.fs.writeFile(path, font.FS.readFile(tfm))
        return path
      })
    },
  }
})()
