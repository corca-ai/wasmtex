#!/usr/bin/env node
/**
 * Generate src/engine/font-scripts.ts — a `{ script: [fontFile, …] }` table of which
 * TeX Live fonts cover which (minority) Unicode scripts, used to suggest a replacement
 * when a document's chosen font has no glyph for the script it uses (#89, L1b).
 *
 * fontconfig already analyses coverage: `fc-scan %{lang}` lists the languages a font
 * supports, which map cleanly to scripts (ko→Hangul, ja→Hiragana/Katakana/Han, …).
 * We run it over a full TeX Live font tree (the texlive/texlive image — no S3 auth),
 * so a suggested font is one the worker can fetch on demand from the mirror.
 *
 * Usage:
 *   # On a host with Docker + the texlive image (remote-builder) — scan + emit:
 *   node scripts/gen-font-scripts.mjs --write
 *   # Or split: capture raw `fc-scan %{file}<US>%{lang}` on the Docker host, then
 *   # parse locally (no Docker needed):
 *   node scripts/gen-font-scripts.mjs --from fc-langs.txt --write
 *
 * Only minority scripts are emitted: a missing Latin/Greek glyph is rare and the
 * candidate set would be enormous; missing CJK/Indic/RTL glyphs are the actionable
 * case (a clear, small font swap).
 */
import { execFileSync } from 'node:child_process'
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const OUT = join(root, 'src/engine/font-scripts.ts')
// Pin to the mirror's TeX Live year so a suggested font is actually fetchable from
// the CDN. `latest` drifts (it's the newest TL) and could surface fonts the 2025
// mirror lacks. Must match the runtime default in wasmtex-engine.ts. Override
// with TEXLIVE_IMAGE when the mirror year changes.
const MIRROR_YEAR = process.env.TEXLIVE_YEAR || '2025'
const TEXLIVE_IMAGE = process.env.TEXLIVE_IMAGE || `texlive/texlive:TL${MIRROR_YEAR}-historic`
const FONT_GLOB = '/usr/local/texlive/*/texmf-dist/fonts'
const SEP = '@@@' // a literal delimiter fc-scan passes through verbatim (\x1f is not)
const MAX_PER_SCRIPT = 24 // cap; the host can show the first few

// fontconfig language code → Unicode script name (matches detectScript() in
// parse-errors.ts). A CJK font covers Han; ja additionally covers the kana.
const LANG_TO_SCRIPTS = {
  ko: ['Hangul', 'Han'],
  ja: ['Hiragana', 'Katakana', 'Han'],
  'zh-cn': ['Han'],
  'zh-tw': ['Han'],
  'zh-hk': ['Han'],
  zh: ['Han'],
  ar: ['Arabic'],
  fa: ['Arabic'],
  ur: ['Arabic'],
  he: ['Hebrew'],
  yi: ['Hebrew'],
  th: ['Thai'],
  hi: ['Devanagari'],
  sa: ['Devanagari'],
  mr: ['Devanagari'],
  ne: ['Devanagari'],
  ru: ['Cyrillic'],
  uk: ['Cyrillic'],
  bg: ['Cyrillic'],
  sr: ['Cyrillic'],
  el: ['Greek'],
}

function scan() {
  // fc-scan inside the texlive image; '%{file}<US>%{lang}\n' per face.
  const script = `fc-scan --format '%{file}${SEP}%{lang}\\n' ${FONT_GLOB} 2>/dev/null`
  return execFileSync(
    'docker',
    ['run', '--rm', '-e', 'OSFONTDIR=', TEXLIVE_IMAGE, 'bash', '-lc', script],
    { encoding: 'utf8', maxBuffer: 512 * 1024 * 1024 },
  )
}

function basename(p) {
  return p.slice(p.lastIndexOf('/') + 1)
}

function main() {
  const fromIdx = process.argv.indexOf('--from')
  if (fromIdx >= 0 && !process.argv[fromIdx + 1]) {
    console.error('usage: --from <fc-scan-output-file>')
    process.exit(2)
  }
  const raw = fromIdx >= 0 ? readFileSync(process.argv[fromIdx + 1], 'utf8') : scan()
  const byScript = new Map() // script → Set<fontFile>
  let faces = 0
  for (const line of raw.split('\n')) {
    if (!line.includes(SEP)) continue
    faces++
    const [file, langField] = line.split(SEP)
    const font = basename(file)
    // Only whole sfnt fonts a user can \setmainfont. Type1 .pfb CJK fonts ship as
    // hundreds of 256-glyph SUBSET files (nanumgtb00.pfb…) with partial, mis-tagged
    // coverage — never a usable suggestion.
    if (!/\.(otf|ttf|ttc|otc)$/i.test(font)) continue
    // fontconfig joins langs with '|'.
    for (const lang of (langField || '').split('|')) {
      const scripts = LANG_TO_SCRIPTS[lang.trim()]
      if (!scripts) continue
      for (const s of scripts) {
        if (!byScript.has(s)) byScript.set(s, new Set())
        byScript.get(s).add(font)
      }
    }
  }

  const table = {}
  for (const [script, fonts] of [...byScript].sort()) {
    table[script] = [...fonts].sort().slice(0, MAX_PER_SCRIPT)
  }

  const ts = `// GENERATED by scripts/gen-font-scripts.mjs — do not edit by hand.
// Fonts on the TeX Live mirror that cover each (minority) Unicode script, for
// suggesting a replacement when a document's font lacks the script's glyphs (#89).
export const SCRIPT_FONTS: Record<string, string[]> = ${JSON.stringify(table, null, 2)}
`

  if (process.argv.includes('--write')) {
    writeFileSync(OUT, ts)
    // Match the repo's formatter so the committed file passes `biome check`.
    execFileSync('npx', ['biome', 'format', '--write', OUT], { cwd: root, stdio: 'ignore' })
    console.error(`Scanned ${faces} faces → wrote ${Object.keys(table).length} scripts to ${OUT}`)
  } else {
    process.stdout.write(ts)
    console.error(`(dry run) scanned ${faces} faces, ${Object.keys(table).length} scripts`)
  }
}

main()
